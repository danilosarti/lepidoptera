"""AI-native extension layer.

`llm_mechanism` and `learned_mechanism` -- any function respecting the
`Mechanism` calling convention is already a valid mechanism (see
mechanism.py), so this module only adds two convenience constructors on
top of that, plus response parsing / model fitting glue. See SPEC.md
section 11.

Neither constructor depends on a specific LLM provider or ML library:
`llm_mechanism` takes any `model` callable (`str -> str`), so it works
with any client (Anthropic SDK, OpenAI SDK, a local model, ...) the
caller wires up; `learned_mechanism` fits directly from a pandas
DataFrame using plain numpy (OLS for continuous outputs, a
k-nearest-neighbors empirical sampler for categorical/ordinal outputs) so
it has no hard dependency on scikit-learn.
"""

from __future__ import annotations

import re
from typing import Any, Callable, Optional, Sequence, Union

import numpy as np
import pandas as pd

from .mechanism import Mechanism

LLMCallable = Callable[[str], str]
Parser = Union[str, Callable[[str], Any]]


def _parse_llm_response(
    response: str,
    output_type: str,
    levels: Optional[Sequence[Any]],
    parser: Parser,
) -> Any:
    if callable(parser):
        return parser(response)
    if parser != "auto":
        raise ValueError("`parser` must be 'auto' or a callable str -> value.")

    text = response.strip()
    if output_type == "continuous":
        match = re.search(r"-?\d+(\.\d+)?", text)
        if not match:
            raise ValueError(f"Could not parse a numeric value from LLM response: {response!r}")
        return float(match.group())

    # categorical / ordinal
    if not levels:
        raise ValueError("`levels` is required to parse a categorical/ordinal LLM response.")
    lowered = text.lower()
    for level in levels:
        if str(level).lower() == lowered:
            return level
    for level in levels:
        if str(level).lower() in lowered:
            return level
    raise ValueError(f"Could not match LLM response {response!r} to any of {list(levels)}.")


def llm_mechanism(
    prompt_template: str,
    model: LLMCallable,
    parents: Sequence[str],
    parent_types: Sequence[str],
    output_type: str,
    levels: Optional[Sequence[Any]] = None,
    parser: Parser = "auto",
) -> Mechanism:
    """A mechanism whose value is generated by an LLM call.

    Parameters
    ----------
    prompt_template:
        A ``str.format``-style template; called as
        ``prompt_template.format(**parent_values)``.
    model:
        Callable ``prompt: str -> response: str``. Bring your own client
        (e.g. ``lambda prompt: anthropic_client.messages.create(...).content[0].text``).
    parents:
        Parent feature names, in the order ``parent_types`` describes them.
    parent_types:
        One :data:`~lepidoptera.type_system.FEATURE_TYPES` entry per
        parent.
    output_type:
        One of the FeatureType values.
    levels:
        Required when ``output_type`` is ``"categorical"``/``"ordinal"``
        -- the response is matched (case-insensitively) against these.
    parser:
        ``"auto"`` (numeric extraction for continuous, level matching for
        categorical/ordinal) or a custom ``str -> value`` callable.

    Returns
    -------
    Mechanism
        Note: not JSON-serializable (``spec`` is ``None``) since it
        carries a live ``model`` callable -- use
        ``register_mechanism()``-style custom systems rather than
        ``export_system()`` for systems that include one.
    """
    if output_type in ("categorical", "ordinal") and not levels:
        raise ValueError("`levels` is required when output_type is categorical/ordinal.")

    def fn(parent_values, rng):
        prompt = prompt_template.format(**parent_values)
        response = model(prompt)
        return _parse_llm_response(response, output_type, levels, parser)

    return Mechanism(
        name="llm_mechanism",
        fn=fn,
        parent_types=tuple(parent_types),
        output_type=output_type,
        spec=None,
    )


def learned_mechanism(
    parents: Sequence[str],
    child: str,
    fit_data: pd.DataFrame,
    uncertainty: str = "auto",
    k: int = 10,
) -> Mechanism:
    """Fit a mechanism directly from observed data.

    v1 scope: `parents` must all be continuous columns of `fit_data`. For
    a continuous `child`, fits OLS (`numpy.linalg.lstsq`) plus Gaussian
    residual noise. For a categorical/ordinal `child`, uses a
    k-nearest-neighbors empirical sampler (`k`) over standardized parent
    space -- at generation time, the `k` nearest fitted observations
    (by Euclidean distance in standardized parent space) are found, and
    the child value is drawn uniformly from their observed values.

    Parameters
    ----------
    parents:
        Continuous parent feature names.
    child:
        Name of the column in `fit_data` to predict (used only to look
        up the column; not stored on the returned Mechanism).
    fit_data:
        A `pandas.DataFrame` with columns `parents + [child]`.
    uncertainty:
        Reserved for future use (e.g. ``"none"`` for a deterministic
        point estimate); currently only the default ``"auto"`` behavior
        described above is implemented.
    k:
        Number of neighbors for the categorical/ordinal branch.

    Returns
    -------
    Mechanism
        Note: not JSON-serializable (``spec`` is ``None``) -- it carries
        the fitted parameters as a closure, not a small parameter dict.
    """
    parents = list(parents)
    X = fit_data[parents].to_numpy(dtype=float)
    y_raw = fit_data[child]

    mean = X.mean(axis=0)
    std = X.std(axis=0)
    std = np.where(std == 0, 1.0, std)
    Xs = (X - mean) / std

    is_continuous = pd.api.types.is_numeric_dtype(y_raw) and not isinstance(
        y_raw.dtype, pd.CategoricalDtype
    )

    if is_continuous:
        y = y_raw.to_numpy(dtype=float)
        design = np.column_stack([np.ones(len(Xs)), Xs])
        coefs, *_ = np.linalg.lstsq(design, y, rcond=None)
        residual_sd = float(np.std(y - design @ coefs))

        def fn(parent_values, rng):
            x = np.array([float(parent_values[p]) for p in parents])
            xs = (x - mean) / std
            pred = coefs[0] + xs @ coefs[1:]
            return float(pred + rng.normal(0.0, residual_sd))

        output_type = "continuous"
    else:
        y = y_raw.to_numpy()
        ordered = isinstance(y_raw.dtype, pd.CategoricalDtype) and y_raw.dtype.ordered
        output_type = "ordinal" if ordered else "categorical"

        def fn(parent_values, rng):
            x = np.array([float(parent_values[p]) for p in parents])
            xs = (x - mean) / std
            dists = np.sqrt(((Xs - xs) ** 2).sum(axis=1))
            neighbor_idx = np.argsort(dists)[: min(k, len(dists))]
            candidates = y[neighbor_idx]
            choice = rng.integers(0, len(candidates))
            return candidates[choice]

    return Mechanism(
        name="learned_mechanism",
        fn=fn,
        parent_types=tuple("continuous" for _ in parents),
        output_type=output_type,
        spec=None,
    )
