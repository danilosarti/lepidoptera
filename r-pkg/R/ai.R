#' Fit a mechanism directly from observed data
#'
#' v1 scope: `parents` must all be continuous columns of `fit_data`. For
#' a continuous `child`, fits OLS + Gaussian residual noise. For a
#' categorical/ordinal `child`, uses a k-nearest-neighbors empirical
#' sampler over standardized parent space.
#'
#' @param parents Character vector of continuous parent feature names.
#' @param child Character. Name of the column in `fit_data` to predict.
#' @param fit_data A `data.frame` with columns `parents` and `child`.
#' @param uncertainty Reserved for future use; currently only `"auto"`
#'   is implemented (OLS + residual noise for continuous, k-NN sampling
#'   for categorical/ordinal).
#' @param k Number of neighbours for the categorical/ordinal branch.
#'
#' @return A `mechanism` object (not JSON-serializable -- `spec` is
#'   `NULL`, since it carries fitted parameters as a closure).
#' @export
learned_mechanism <- function(parents, child, fit_data,
                               uncertainty = "auto", k = 10L) {
  parents <- as.character(parents)
  X <- as.matrix(fit_data[, parents, drop = FALSE])
  storage.mode(X) <- "double"
  y_raw <- fit_data[[child]]

  col_mean <- colMeans(X)
  col_sd   <- apply(X, 2, sd)
  col_sd[col_sd == 0] <- 1
  Xs <- scale(X, center = col_mean, scale = col_sd)

  is_continuous <- is.numeric(y_raw) && !is.factor(y_raw)

  if (is_continuous) {
    y <- as.double(y_raw)
    design <- cbind(1, Xs)
    coefs  <- as.double(qr.solve(design, y))
    resid_sd <- sd(y - design %*% coefs)

    fn <- function(parent_values) {
      x  <- as.double(sapply(parents, function(p) parent_values[[p]]))
      xs <- (x - col_mean) / col_sd
      pred <- coefs[1] + sum(xs * coefs[-1])
      pred + rnorm(1, 0, resid_sd)
    }
    output_type <- "continuous"

  } else {
    y    <- as.character(y_raw)
    ordered <- is.ordered(y_raw)
    output_type <- if (ordered) "ordinal" else "categorical"

    fn <- function(parent_values) {
      x  <- as.double(sapply(parents, function(p) parent_values[[p]]))
      xs <- (x - col_mean) / col_sd
      # Euclidean distance in standardized space
      diffs <- sweep(Xs, 2, xs)
      dists <- sqrt(rowSums(diffs^2))
      nn    <- order(dists)[seq_len(min(k, length(dists)))]
      sample(y[nn], size = 1)
    }
  }

  .new_mechanism("learned_mechanism", fn, rep("continuous", length(parents)), output_type, spec = NULL)
}

# --------------------------------------------------------------------------
# model_mechanism  -- wrap any pre-fitted R model as a generative mechanism
# --------------------------------------------------------------------------

#' Wrap a pre-fitted model as a generative mechanism
#'
#' Turns any model object the user has already trained (a `ranger` random
#' forest, a `glm`, an `xgboost` booster, a `keras` network, ...) into a
#' standard lepidoptera `mechanism`.  The user provides a single
#' `predict_fn` that accepts a named `list` of parent values and returns one
#' predicted value.
#'
#' @details
#' This differs from [learned_mechanism()] in a fundamental way:
#' `learned_mechanism()` **fits** a model internally on `fit_data`;
#' `model_mechanism()` **uses** a model that was already fitted outside
#' lepidoptera.  The user is responsible for the predict function, including
#' reshaping inputs, choosing the right output slot, and optionally adding
#' stochastic noise.
#'
#' **Quick patterns:**
#' ```r
#' # ranger random forest
#' rf <- ranger::ranger(outcome ~ age + bp, data = df, probability = TRUE)
#' mech <- model_mechanism(
#'   predict_fn   = function(pv) {
#'     nd   <- data.frame(age = as.numeric(pv$age), bp = as.numeric(pv$bp))
#'     pred <- predict(rf, nd)$predictions
#'     sample(colnames(pred), 1, prob = pred[1,])
#'   },
#'   parents      = c("age", "bp"),
#'   parent_types = c("continuous", "continuous"),
#'   output_type  = "categorical",
#'   levels       = c("no_response", "response")
#' )
#'
#' # glm  (logistic regression)
#' fit <- glm(response ~ age + dose, data = trial, family = binomial)
#' mech <- model_mechanism(
#'   predict_fn   = function(pv) {
#'     nd <- data.frame(age = as.numeric(pv$age), dose = as.numeric(pv$dose))
#'     p  <- predict(fit, nd, type = "response")[[1]]
#'     sample(c("yes","no"), 1, prob = c(p, 1-p))
#'   },
#'   parents      = c("age", "dose"),
#'   parent_types = c("continuous", "continuous"),
#'   output_type  = "categorical",
#'   levels       = c("yes", "no")
#' )
#'
#' # lm  (linear regression) with residual noise
#' fit_lm <- lm(sbp ~ age + bmi, data = cohort)
#' sigma  <- summary(fit_lm)$sigma
#' mech <- model_mechanism(
#'   predict_fn   = function(pv) {
#'     nd   <- data.frame(age = as.numeric(pv$age), bmi = as.numeric(pv$bmi))
#'     pred <- predict(fit_lm, nd)[[1]]
#'     pred + rnorm(1, 0, sigma)          # add residual noise manually
#'   },
#'   parents      = c("age", "bmi"),
#'   parent_types = c("continuous", "continuous"),
#'   output_type  = "continuous"
#' )
#' ```
#'
#' @param predict_fn A function `function(parent_values)` where
#'   `parent_values` is a named list (same structure as inside any mechanism
#'   `fn`).  Must return a **single** value compatible with `output_type`.
#'   The function is called once per simulated unit; use R's RNG directly
#'   inside it for stochastic outputs.
#' @param parents Character vector of parent feature names (must match the
#'   names present in `parent_values` at generation time).
#' @param parent_types Character vector of [feature_types()], one per parent,
#'   in the same order as `parents`.
#' @param output_type One of [feature_types()].
#' @param levels Required when `output_type` is `"categorical"` or
#'   `"ordinal"` -- used only for documentation / validation; the actual
#'   return value is whatever `predict_fn` produces.
#' @param name Optional character label stored in the mechanism object.
#'   Defaults to `"model_mechanism"`.
#'
#' @return A `mechanism` object (not JSON-serializable -- `spec = NULL`).
#' @export
model_mechanism <- function(predict_fn, parents, parent_types, output_type,
                             levels = NULL, name = "model_mechanism") {
  if (!is.function(predict_fn)) stop("`predict_fn` must be a function.")
  if (length(parents) != length(parent_types)) {
    stop("`parents` and `parent_types` must have the same length.")
  }
  if (output_type %in% c("categorical", "ordinal") && is.null(levels)) {
    warning(paste0(
      "`levels` not supplied for output_type = '", output_type, "'. ",
      "Validation downstream may be incomplete."
    ), call. = FALSE)
  }

  force(predict_fn); force(parents); force(parent_types)
  force(output_type); force(levels)

  fn <- function(parent_values) {
    predict_fn(parent_values)
  }

  .new_mechanism(name, fn, parent_types, output_type, spec = NULL)
}
