# AI-native extension layer ------------------------------------------------
#
# Three constructors, each returning a standard `mechanism` object that
# slots into any System without special treatment.  See SPEC.md section 11.
#
#   llm_mechanism()     -- calls an external LLM at generation time
#   learned_mechanism() -- fits OLS / k-NN from data internally
#   model_mechanism()   -- wraps ANY pre-fitted R model object
#
# Calling convention: fn(parent_values) using R's global RNG (set.seed()
# per unit by simulate.R / propagate.R), consistent with the rest of the
# mechanism library.

# --------------------------------------------------------------------------
# LLM mechanism
# --------------------------------------------------------------------------

.parse_llm_response <- function(response, output_type, levels, parser) {
  if (is.function(parser)) return(parser(response))
  if (!identical(parser, "auto")) stop("`parser` must be 'auto' or a function.")

  text <- trimws(response)
  if (output_type == "continuous") {
    m <- regmatches(text, regexpr("-?[0-9]+\\.?[0-9]*", text))
    if (length(m) == 0 || nchar(m) == 0) {
      stop(sprintf("Could not parse a numeric value from LLM response: %s", dQuote(text)))
    }
    return(as.numeric(m))
  }

  # categorical / ordinal: match against levels
  if (is.null(levels)) stop("`levels` is required to parse a categorical/ordinal LLM response.")
  low <- tolower(text)
  for (lvl in levels) if (identical(tolower(as.character(lvl)), low)) return(lvl)
  for (lvl in levels) if (grepl(tolower(as.character(lvl)), low, fixed = TRUE)) return(lvl)
  stop(sprintf("Could not match LLM response %s to any of: %s.",
               dQuote(text), paste(as.character(levels), collapse = ", ")))
}

#' A mechanism whose value is generated by an LLM call
#'
#' @param prompt_template A `glue`/`sprintf`-free template for
#'   [base::sprintf()] -- or, more flexibly, a function
#'   `function(parent_values)` returning the prompt string directly.
#'   When a character string is supplied it is formatted with
#'   [base::do.call()] + `format`, substituting named parent values.
#' @param model Function `function(prompt_text)` returning a string (the
#'   LLM response). Supply any client you like, e.g.
#'   `function(p) httr2::resp_body_json(...)$content[[1]]$text`.
#' @param parents Character vector of parent feature names.
#' @param parent_types Character vector, one [feature_types()] entry per
#'   parent.
#' @param output_type One of [feature_types()].
#' @param levels Required when `output_type` is `"categorical"` or
#'   `"ordinal"` -- the response is matched (case-insensitively) against
#'   these.
#' @param parser `"auto"` (numeric extraction for continuous, level
#'   matching for categorical/ordinal) or a custom `function(response)`
#'   returning the parsed value.
#'
#' @return A `mechanism` object (not JSON-serializable -- `spec` is
#'   `NULL`, since it carries a live `model` function).
#' @export
llm_mechanism <- function(prompt_template, model, parents, parent_types,
                           output_type, levels = NULL, parser = "auto") {
  if (output_type %in% c("categorical", "ordinal") && is.null(levels)) {
    stop("`levels` is required when output_type is categorical/ordinal.")
  }
  force(prompt_template); force(model); force(parents)
  force(output_type); force(levels); force(parser)

  fn <- function(parent_values) {
    prompt <- if (is.function(prompt_template)) {
      prompt_template(parent_values)
    } else {
      # substitute {name} placeholders a la Python str.format
      txt <- prompt_template
      for (nm in names(parent_values)) {
        txt <- gsub(paste0("{", nm, "}"), as.character(parent_values[[nm]]), txt, fixed = TRUE)
      }
      txt
    }
    response <- model(prompt)
    .parse_llm_response(response, output_type, levels, parser)
  }

  .new_mechanism("llm_mechanism", fn, parent_types, output_type, spec = NULL)
}

